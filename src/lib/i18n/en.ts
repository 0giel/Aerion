/** Plural forms per `Intl.PluralRules` category (Polish uses one/few/many). */
export type Plural = { zero?: string; one: string; few?: string; many?: string; other: string };
type Widen<T> = T extends string
  ? string
  : T extends { one: string; other: string }
    ? Plural
    : { [K in keyof T]: Widen<T[K]> };
export type Dict = Widen<typeof en>;
