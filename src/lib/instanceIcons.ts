export const ICON_KEYS = Object.keys(INSTANCE_ICONS);

export interface PixelRect {
  x: number;
  y: number;
  w: number;
  fill: string;
}

const cache = new Map<string, PixelRect[]>();

/** Horizontal runs of one colour, so an icon is ~40 rectangles instead of ~200. */
export function iconRects(key: string): PixelRect[] {
  const hit = cache.get(key);
  if (hit) return hit;
  const icon = INSTANCE_ICONS[key];
  const rects: PixelRect[] = [];
  icon?.rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (row[x + w] === ch) w++;
      if (ch !== ".") rects.push({ x, y, w, fill: icon.palette[ch] });
      x += w;
    }
  });
  cache.set(key, rects);
  return rects;
}
