/// Write `src/lib/bindings.ts` (debug builds do this on start; CI checks it is up to date).
pub fn export_bindings(path: &std::path::Path) {
    specta_builder()
        .export(
            specta_typescript::Typescript::default().header(
                "// Generated by tauri-specta from src-tauri. Do not edit.\n// @ts-nocheck",
            ),
            path,
        )
        .expect("export TypeScript bindings");
}

fn init_tracing() {
    use tracing_subscriber::prelude::*;
    let default = if cfg!(debug_assertions) {
        "info,luncher_lib=debug,launcher_core=debug"
    } else {
        "info"
    };
    let filter =
        tracing_subscriber::EnvFilter::try_from_default_env().unwrap_or_else(|_| default.into());
    let file_layer = launcher_core::paths::Paths::detect().ok().and_then(|p| {
        std::fs::create_dir_all(p.logs_dir()).ok()?;
        let appender = tracing_appender::rolling::RollingFileAppender::builder()
            .rotation(tracing_appender::rolling::Rotation::DAILY)
            .filename_prefix("luncher")
            .filename_suffix("log")
            .max_log_files(7)
            .build(p.logs_dir())
            .ok()?;
        let (writer, guard) = tracing_appender::non_blocking(appender);
        // Keep the writer alive for the whole process.
        std::mem::forget(guard);
        Some(
            tracing_subscriber::fmt::layer()
                .with_ansi(false)
                .with_writer(writer),
        )
    });
    let _ = tracing_subscriber::registry()
        .with(filter)
        .with(tracing_subscriber::fmt::layer().with_writer(std::io::stderr))
        .with(file_layer)
        .try_init();
}

pub(crate) fn show_main(app: &AppHandle) {
    let Some(w) = app.get_webview_window("main") else {
        return;
    };
    // Some X11 window managers (Mutter) ignore de-iconify requests; re-mapping a hidden
    // window always brings it back un-minimized.
    if w.is_minimized().unwrap_or(false) {
        let _ = w.hide();
    }
    let _ = w.show();
    let _ = w.unminimize();
    let _ = w.set_focus();
}

/// `--launch <instance id>` (desktop shortcuts).
fn launch_arg(args: &[String]) -> Option<String> {
    args.iter()
        .position(|a| a == "--launch")
        .and_then(|i| args.get(i + 1))
        .cloned()
}

fn handle_launch_arg(app: &AppHandle, args: &[String]) {
    if let Some(id) = launch_arg(args) {
        let app = app.clone();
        tauri::async_runtime::spawn(async move {
            let state = app.state::<AppState>();
            if let Err(e) = commands::launch::start_launch(&app, &state, id, None).await {
                tracing::warn!(error = %e.message, "launch from shortcut failed");
                show_main(&app);
            }
        });
    }
}

fn setup_tray(app: &tauri::App) -> tauri::Result<()> {
    let show = MenuItem::with_id(app, "show", "Luncher", true, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", "Zakończ / Quit", true, None::<&str>)?;
    let menu = Menu::with_items(app, &[&show, &quit])?;
    let mut tray = TrayIconBuilder::with_id("main")
        .tooltip("Luncher")
        .menu(&menu)
        .show_menu_on_left_click(false)
        .on_menu_event(|app, event| match event.id().as_ref() {
            "show" => show_main(app),
            "quit" => app.exit(0),
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                show_main(tray.app_handle());
            }
        });
    if let Some(icon) = app.default_window_icon() {
        tray = tray.icon(icon.clone());
    }
    tray.build(app)?;
    Ok(())
}

/// Debug builds only: evaluates the file's contents in the main webview whenever it changes, so
/// UI flows can be scripted without driving the mouse. Results come back via the console mirror.
#[cfg(debug_assertions)]
fn dev_eval(app: AppHandle, file: std::path::PathBuf) {
    tauri::async_runtime::spawn(async move {
        let mtime = || std::fs::metadata(&file).and_then(|m| m.modified()).ok();
        // Only changes made after start-up are evaluated.
        let mut last = mtime();
        loop {
            tokio::time::sleep(std::time::Duration::from_millis(300)).await;
            let now = mtime();
            if now.is_none() || now == last {
                continue;
            }
            last = now;
            if let (Ok(code), Some(w)) = (
                std::fs::read_to_string(&file),
                app.get_webview_window("main"),
            ) {
                tracing::debug!(bytes = code.len(), "dev eval");
                let _ = w.eval(format!("(async () => {{ try {{ {code}\n }} catch (e) {{ console.error('dev eval', e); }} }})()"));
            }
        }
    });
}

pub fn run(platform_notes: Vec<String>) {
    init_tracing();
    tracing::info!(version = env!("CARGO_PKG_VERSION"), "Luncher starting");
    for note in platform_notes {
        tracing::warn!("{note}");
    }
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(std::path::Path::new(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../src/lib/bindings.ts"
    )));

    tauri::Builder::default()
        .plugin(tauri_plugin_single_instance::init(|app, args, _cwd| {
            show_main(app);
            handle_launch_arg(app, &args);
        }))
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_window_state::Builder::default().with_state_flags(StateFlags::all() & !StateFlags::VISIBLE).build())
        .register_asynchronous_uri_scheme_protocol("img", protocols::img)
        .register_asynchronous_uri_scheme_protocol("themeasset", protocols::theme_asset)
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let state = tauri::async_runtime::block_on(AppState::init()).map_err(|e| e.to_string())?;
            let themes_dir = state.paths.themes_dir();
            let cache = state.paths.image_cache_dir();
            app.manage(state);
            themes::install_schema(&themes_dir);
            themes::watch(app.handle().clone(), themes_dir);
            tauri::async_runtime::spawn(protocols::trim_image_cache(cache));
            if let Err(e) = setup_tray(app) {
                tracing::warn!(error = %e, "system tray unavailable");
            }
            // The UI shows the window once the theme is applied; this is a safety net.
            let handle = app.handle().clone();
            tauri::async_runtime::spawn(async move {
                tokio::time::sleep(std::time::Duration::from_secs(4)).await;
                if let Some(w) = handle.get_webview_window("main")
                    && !w.is_visible().unwrap_or(true)
                {
                    let _ = w.show();
                }
            });
            // Development aid: keep the window above others (used for automated screenshots).
            if cfg!(debug_assertions)
                && std::env::var_os("LUNCHER_DEV_ON_TOP").is_some()
                && let Some(w) = app.get_webview_window("main")
            {
                let _ = w.set_always_on_top(true);
            }
            #[cfg(all(debug_assertions, target_os = "linux"))]
            if let Some(w) = app.get_webview_window("main") {
                // Mirror the page's console (including uncaught errors) to stdout.
                let _ = w.with_webview(|wv| {
                    use webkit2gtk::{SettingsExt, WebViewExt};
                    if let Some(s) = wv.inner().settings() {
                        s.set_enable_write_console_messages_to_stdout(true);
                    }
                });
            }
            #[cfg(debug_assertions)]
            if let Some(file) = std::env::var_os("LUNCHER_DEV_EVAL") {
                dev_eval(app.handle().clone(), file.into());
            }
            let args: Vec<String> = std::env::args().collect();
            handle_launch_arg(app.handle(), &args);
            Ok(())
        })
        .on_page_load(|webview, payload| {
            tracing::debug!(label = webview.label(), url = %payload.url(), event = ?payload.event(), "page load");
        })
        .on_window_event(|window, event| {
            if let WindowEvent::CloseRequested { api, .. } = event {
                let state = window.app_handle().state::<AppState>();
                let to_tray = state.settings.try_read().map(|s| s.close_to_tray).unwrap_or(false);
                if to_tray {
                    api.prevent_close();
                    let _ = window.hide();
                }
            }
        })
        .run(tauri::generate_context!())
        .expect("error while running Luncher");
}

